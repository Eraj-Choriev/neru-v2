#!/usr/bin/env node
// Generates js/config.js from environment variables (or a local .env).
//
//   Vercel:  runs automatically as the project's buildCommand (vercel.json);
//            set the variables in Project Settings → Environment Variables.
//   Local:   cp .env.example .env, fill it in, then `node scripts/build-config.mjs`.
//
// Real environment variables win over .env. Without NUR_2GIS_KEY the committed
// js/config.js is kept as it is (temporary: the keys are in the repo until the
// Vercel project has its environment variables). Only if that file is missing
// too does the build fail, so a deploy never ships a map that cannot load.
//
// Note: both values end up in the browser — that is how a browser map key and
// a web-analytics beacon work. Their protection is the Referer allow-list in
// the 2GIS Platform Manager and Cloudflare's domain binding, not secrecy.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function readDotEnv(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

const env = { ...readDotEnv(resolve(root, '.env')), ...process.env };
const mapKey = (env.NUR_2GIS_KEY || '').trim();
const beaconToken = (env.NUR_CF_BEACON_TOKEN || '').trim();

const target = resolve(root, 'js/config.js');
if (!mapKey) {
  if (existsSync(target)) {
    console.warn('⚠ NUR_2GIS_KEY is not set — keeping the committed js/config.js.');
    process.exit(0);
  }
  console.error('✖ NUR_2GIS_KEY is not set and js/config.js is missing. Add it to .env (local) or to the Vercel project environment variables.');
  process.exit(1);
}
// Keys are pasted by hand; reject anything that is not a plain token.
for (const [name, value] of [['NUR_2GIS_KEY', mapKey], ['NUR_CF_BEACON_TOKEN', beaconToken]]) {
  if (value && !/^[A-Za-z0-9_-]{8,128}$/.test(value)) {
    console.error(`✖ ${name} has an unexpected format.`);
    process.exit(1);
  }
}

const config = `// GENERATED by scripts/build-config.mjs from environment variables.
// Committed for now so deploys work without Vercel env vars; once
// NUR_2GIS_KEY is set there, the build regenerates this file.
window.NUR_MAP_CONFIG = Object.freeze({
  key: ${JSON.stringify(mapKey)},
  center: [68.7738, 38.5598], // Dushanbe, [lng, lat]
});
window.NUR_ANALYTICS_TOKEN = ${JSON.stringify(beaconToken)};
`;

writeFileSync(target, config);
console.log(`✔ js/config.js written (2GIS key …${mapKey.slice(-4)}, analytics ${beaconToken ? 'on' : 'off'})`);
